-- AROMA: shaxsiy kuponlar, asosiy kuponlar va buyurtma RPC-ni buzmasdan ishlaydi.
-- BIRINCHI shu SQLni Supabase SQL Editor'da bajaring, KEYIN kodni deploy qiling.
-- Joriy aroma_place_order_v2 va v1 funksiyalarini almashtirmaydi.
BEGIN;
SET LOCAL lock_timeout = '8s';

CREATE TABLE IF NOT EXISTS public.personal_coupons (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (code ~ '^VIP-[A-Z0-9]{10,20}$'),
    customer_id text NOT NULL CHECK (customer_id ~ '^[1-9][0-9]{0,19}$'),
    discount_type text NOT NULL CHECK (discount_type IN ('fixed','percent')),
    discount_value numeric(14,2) NOT NULL CHECK (discount_value > 0 AND discount_value <= 1000000000),
    min_order_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (min_order_amount >= 0 AND min_order_amount <= 1000000000),
    expires_at timestamptz NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    used_at timestamptz,
    used_order_id text UNIQUE,
    CONSTRAINT personal_coupon_pct_check CHECK (discount_type <> 'percent' OR discount_value <= 100),
    CONSTRAINT personal_coupon_used_state CHECK ((used_at IS NULL) = (used_order_id IS NULL))
);
CREATE INDEX IF NOT EXISTS aroma_personal_coupon_customer_idx ON public.personal_coupons(customer_id,created_at DESC);
ALTER TABLE public.personal_coupons ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.personal_coupons FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.personal_coupons TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.personal_coupons_id_seq TO service_role;

ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS personal_coupon_id bigint;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS personal_coupon_discount_amount numeric NOT NULL DEFAULT 0;
-- The original coupon_discount_amount contains the SUM of regular and personal coupon discounts.
-- Thus old totals remain consistent: original_total - product_discount_amount - coupon_discount_amount = total.

-- Admin-only phone lookup. Multiple Telegram accounts with the same phone are *not* silently conflated.
CREATE OR REPLACE FUNCTION public.aroma_find_personal_coupon_customer_v1(p_phone text)
RETURNS TABLE(customer_id text, customer_name text, phone text)
LANGUAGE sql STABLE SECURITY INVOKER
SET search_path = pg_catalog, public
AS $lookup$
  WITH digits AS (
      SELECT regexp_replace(coalesce(p_phone,''), '[^0-9]', '', 'g') AS d
  ), search_phone AS (
      SELECT CASE WHEN length(d)=9 THEN '998'||d ELSE d END AS d FROM digits
  ), matches AS (
      SELECT DISTINCT ON (o.customer_id) o.customer_id, o.customer_name, o.phone, o.order_date
      FROM public.orders o, search_phone s
      WHERE length(s.d) BETWEEN 11 AND 15
        AND (CASE WHEN length(regexp_replace(coalesce(o.phone,''),'[^0-9]','','g'))=9
              THEN '998'||regexp_replace(o.phone,'[^0-9]','','g')
              ELSE regexp_replace(coalesce(o.phone,''),'[^0-9]','','g') END) = s.d
      ORDER BY o.customer_id, o.order_date DESC
  )
  SELECT m.customer_id, m.customer_name, m.phone FROM matches m
  ORDER BY m.order_date DESC LIMIT 3;
$lookup$;
REVOKE ALL ON FUNCTION public.aroma_find_personal_coupon_customer_v1(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.aroma_find_personal_coupon_customer_v1(text) TO service_role;

-- A single transaction: verifies owner and minimum using actual server prices, consumes once,
-- saves the DISCOUNTED order, and returns the actual discounted receipt to the bot.
CREATE OR REPLACE FUNCTION public.aroma_place_order_v3(
    p_customer_id text, p_customer_name text, p_customer_username text,
    p_phone text, p_address text, p_items jsonb, p_coupon_code text, p_request_key text,
    p_personal_coupon_id bigint
) RETURNS jsonb
LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public
SET lock_timeout = '8s'
AS $order$
DECLARE
    v_coupon public.personal_coupons%ROWTYPE;
    v_result jsonb;
    v_existing public.orders%ROWTYPE;
    v_updated public.orders%ROWTYPE;
    v_eligible_subtotal numeric;
    v_before_personal numeric;
    v_discount numeric;
    v_final numeric;
    v_reason text;
    v_settings public.shop_settings%ROWTYPE;
BEGIN
    -- A retried request must return the already-committed order, not consume twice.
    IF p_customer_id IS NULL OR p_customer_id !~ '^[1-9][0-9]{0,19}$'
       OR p_request_key IS NULL OR p_request_key !~ '^[A-Za-z0-9:_-]{1,160}$' THEN
       RAISE EXCEPTION 'Buyurtma kaliti noto‘g‘ri' USING ERRCODE='P0001';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended(p_customer_id || ':' || p_request_key, 0));
    SELECT * INTO v_existing FROM public.orders
        WHERE customer_id=p_customer_id AND request_key=p_request_key;
    IF FOUND THEN
        -- The original v2/v1 checks the request fingerprint to prevent replay with different items.
        RETURN public.aroma_place_order_v2(p_customer_id,p_customer_name,p_customer_username,
            p_phone,p_address,p_items,p_coupon_code,p_request_key);
    END IF;
    BEGIN
        SELECT * INTO v_coupon FROM public.personal_coupons
         WHERE id=p_personal_coupon_id FOR UPDATE;
        IF NOT FOUND OR v_coupon.customer_id IS DISTINCT FROM p_customer_id THEN
            RAISE EXCEPTION 'Shaxsiy kupon sizning akkauntingizga tegishli emas' USING ERRCODE='P0001';
        END IF;
        IF v_coupon.active IS NOT TRUE OR v_coupon.used_at IS NOT NULL OR clock_timestamp() >= v_coupon.expires_at THEN
            RAISE EXCEPTION 'Shaxsiy kupon faol emas yoki muddati tugagan' USING ERRCODE='P0001';
        END IF;
        -- Computes stock, product/category and standard-coupon reductions using trusted DB values.
        v_result := public.aroma_place_order_v2(p_customer_id,p_customer_name,p_customer_username,
            p_phone,p_address,p_items,p_coupon_code,p_request_key);
        IF v_result->>'rejected' = 'true' OR v_result->>'duplicate' = 'true' THEN
            RETURN v_result;
        END IF;
        IF v_result->'order'->>'id' IS NULL THEN
            RAISE EXCEPTION 'Buyurtma natijasi olinmadi' USING ERRCODE='P0001';
        END IF;
        -- Personal minimum: after product/category discounts, BEFORE BOTH coupons.
        v_eligible_subtotal := coalesce((v_result->'order'->>'original_total')::numeric,0)
                            - coalesce((v_result->'order'->>'product_discount_amount')::numeric,0);
        IF v_eligible_subtotal <= 0 OR v_eligible_subtotal < v_coupon.min_order_amount THEN
            RAISE EXCEPTION 'Shaxsiy kupon uchun minimal xarid summasi yetarli emas' USING ERRCODE='P0001';
        END IF;
        v_before_personal := coalesce((v_result->'order'->>'total')::numeric,0);
        v_discount := CASE WHEN v_coupon.discount_type='fixed' THEN v_coupon.discount_value
                   ELSE round(v_before_personal * v_coupon.discount_value / 100) END;
        v_discount := least(greatest(0, v_discount), v_before_personal);
        IF v_discount <= 0 THEN
            RAISE EXCEPTION 'Shaxsiy kupon bu buyurtmaga qo‘llanmaydi' USING ERRCODE='P0001';
        END IF;
        v_final := v_before_personal-v_discount;
        SELECT * INTO v_settings FROM public.shop_settings ORDER BY id LIMIT 1;
        UPDATE public.orders SET
           total=v_final,
           coupon_discount_amount=coalesce(coupon_discount_amount,0)+v_discount,
           personal_coupon_discount_amount=v_discount,
           personal_coupon_id=v_coupon.id,
           free_delivery=coalesce(v_settings.free_delivery_enabled AND v_final>=v_settings.free_delivery_min_amount,false)
        WHERE id=v_result->'order'->>'id' AND customer_id=p_customer_id
        RETURNING * INTO v_updated;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Shaxsiy kuponli buyurtmani saqlab bo‘lmadi' USING ERRCODE='P0001';
        END IF;
        UPDATE public.personal_coupons SET used_at=clock_timestamp(), used_order_id=v_updated.id
         WHERE id=v_coupon.id AND used_at IS NULL;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Shaxsiy kupon allaqachon ishlatilgan' USING ERRCODE='P0001';
        END IF;
        RETURN jsonb_set(v_result,'{order}',to_jsonb(v_updated));
    EXCEPTION WHEN SQLSTATE 'P0001' THEN
        -- Save a rejected receipt; rollback any intermediate order/stock/coupon effects.
        GET STACKED DIAGNOSTICS v_reason=MESSAGE_TEXT;
        INSERT INTO public.order_receipt_failures(request_key,customer_id,reason)
            VALUES(p_request_key,p_customer_id,left(v_reason,500)) ON CONFLICT DO NOTHING;
        RETURN jsonb_build_object('rejected',true,'message',v_reason);
    END;
END;
$order$;
REVOKE ALL ON FUNCTION public.aroma_place_order_v3(text,text,text,text,text,jsonb,text,text,bigint)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.aroma_place_order_v3(text,text,text,text,text,jsonb,text,text,bigint)
    TO service_role;
NOTIFY pgrst, 'reload schema';
COMMIT;
SELECT 'Aroma: shaxsiy kuponlar va xavfsiz buyurtma v3 tayyor' AS result;
